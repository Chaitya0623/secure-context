"""Self-contained presentation walkthrough with no datasets or API calls."""
import streamlit as st

from secure_context.tokens import Session, rehydrate


def render_demo():
    st.title("From private client record to useful AI context")
    st.info("Guided example: fictional client, illustrative policy choices and scripted answer. "
            "No API calls are made. This walkthrough does not depend on evaluation completion.")
    st.caption("Advisor task: prepare a meeting brief for Maya Patel. "
               "Turn off Guided demo in the sidebar to explore the interactive benchmark app.")
    if "guided_session" not in st.session_state:
        st.session_state.guided_session = Session()
    session = st.session_state.guided_session
    person = session.token("PERSON", "Maya Patel")
    email = session.token("EMAIL", "maya@example.com")
    steps = ["1. Raw record", "2. Identify PII", "3. Split storage", "4. Tokenize",
             "5. Minimize context", "6. Model boundary", "7. Restore the answer"]
    step = st.radio("Walkthrough step", steps, key="guided_step")
    idx = steps.index(step)
    st.progress((idx + 1) / len(steps), text=f"Step {idx + 1} of {len(steps)}")
    raw = ("Name: Maya Patel\nEmail: maya@example.com\nAge: 47\nLocation: Boston, MA\n"
           "Occupation: Surgeon\nAssets: $3.2 million\nObjective: Retirement planning\n"
           "Risk tolerance: Moderate\nHorizon: 15 years\nLiquidity: $80,000 within 12 months")
    prompt = (f"Task: Prepare meeting brief.\nClient ref: {person}\nContact ref: {email}\n"
              "Age: 40-49\nAssets: $1M-$5M\nObjective: Retirement planning\n"
              "Risk tolerance: Moderate\nTime horizon: 15 years\n"
              "Liquidity need: $50K-$150K within a year")
    answer = (f"Meeting brief for {person}:\n"
              "1. Review retirement goals and the 15-year horizon.\n"
              "2. Discuss moderate risk tolerance.\n"
              "3. Confirm the upcoming liquidity need; the exact amount was not shared.\n"
              f"Send the agenda to {email}.")
    explanations = [
        "The advisor needs a useful meeting brief. Sending the whole client record would disclose more than that task requires.",
        "Direct identifiers identify a person immediately. Quasi-identifiers, such as age and occupation, can identify them in combination.",
        "Identity and financial context are kept in separate stores. A trusted local service holds the link between their random IDs.",
        "The model can refer to the client consistently using a temporary token. The original value and session key remain local.",
        "Choose the least revealing representation that preserves useful task information, subject to the configured crowd-size constraint.",
        "Only the selected prompt crosses the answer-generation boundary. This walkthrough displays a scripted answer, not a Groq response.",
        "Restore known tokens locally so the advisor sees a readable answer. Unknown or ambiguous tokens are flagged for review.",
    ]
    st.subheader(steps[idx])
    st.write(explanations[idx])
    left, right = st.columns(2)
    if idx == 0:
        left.code(raw, language=None)
        right.markdown("**Say:** ‘We want the model to understand the task without receiving the entire client identity and financial record.’")
    elif idx == 1:
        left.table({"Direct identifier": ["Maya Patel", "maya@example.com"], "Label": ["PERSON", "EMAIL"]})
        right.table({"Potential linkage attributes": ["Age 47", "Boston", "Surgeon", "$3.2 million"]})
    elif idx == 2:
        left.markdown("**Identity vault, local**\n\nName, email, token mappings and the context-to-identity link.")
        right.markdown("**Context store, local**\n\nFinancial profile, holdings and tokenized notes under a separate random context ID.")
        st.caption("Prototype: separate SQLite stores with application role checks. AES-GCM encrypts selected identifier fields, not the entire vault.")
    elif idx == 3:
        left.code("Maya Patel\nmaya@example.com", language=None)
        right.code(f"{person}\n{email}", language=None)
        st.caption("These tokens are generated by the actual Session implementation, using HMAC-SHA256 and a random session key.")
        if st.button("Rotate demo session key"):
            st.session_state.guided_session = Session()
            st.rerun()
    elif idx == 4:
        st.table({"Field": ["Age", "Location", "Occupation", "Assets", "Liquidity", "Objective / risk / horizon"],
                  "Original": ["47", "Boston", "Surgeon", "$3.2M", "$80K within 12 months", "Task-relevant values"],
                  "Illustrative shared view": ["40-49", "Omitted", "Omitted", "$1M-$5M", "$50K-$150K within a year", "Retained"]})
        st.warning("No crowd-size or utility score is measured in this example. The interactive app computes them against its reference directory.")
        st.write("Across repeated requests, the exposure ledger combines earlier disclosures with the proposed context before checking the threshold.")
    elif idx == 5:
        left.markdown("**Outgoing prompt**")
        left.code(prompt, language=None)
        right.markdown("**Scripted model answer**")
        right.code(answer, language=None)
    else:
        left.markdown("**Answer with tokens**")
        left.code(answer, language=None)
        right.markdown("**Advisor view, restored locally**")
        restored = rehydrate(answer, session)
        right.code(restored.text, language=None)
        st.success(f"{restored.resolved} tokens restored by the actual rehydrator; {len(restored.unresolved)} unresolved.")
        st.write("Next: turn off Guided demo to compare masking and adaptive policies, inspect cumulative exposure, and review saved baseline results.")
    with st.expander("Presenter notes and limitations"):
        st.write("This is a walkthrough of the design, not evidence of model quality or a guarantee of anonymity. "
                 "The adaptive policy uses a rule-based utility score and a modeled crowd size. "
                 "Saved benchmark results are separate from this fictional example and are not completed Groq results. "
                 "Hosted PII detection and unprotected evaluation baselines can send original benchmark text to a provider; "
                 "the protected answer-generation boundary illustrated here is a distinct step.")
